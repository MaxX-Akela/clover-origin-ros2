#!/usr/bin/env bash

#
# Script for the final cleanup of the image (runs inside the image chroot):
# everything that must be created again on the first boot is removed.
# The cloud-init seed on /boot/firmware stays.
#
# Part of the ROS 2 port of Clover (https://github.com/CopterExpress/clover).
#
